-- Restaurant Event Order (REO) for Sales Leads

CREATE TABLE IF NOT EXISTS `sales_lead_reos` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `sales_lead_id` BIGINT UNSIGNED NOT NULL,
  `number` VARCHAR(255) NOT NULL,
  `company_name` VARCHAR(255) NOT NULL,
  `address` TEXT NULL,
  `contact_person` VARCHAR(255) NULL,
  `mobile` VARCHAR(255) NULL,
  `email` VARCHAR(255) NULL,
  `date_of_issue` DATE NULL,
  `venue_setup` VARCHAR(255) NULL,
  `sales_person_user_id` BIGINT UNSIGNED NULL,
  `sales_person_name` VARCHAR(255) NULL,
  `sign_board` TEXT NULL,
  `revenue_items` JSON NULL,
  `catering_fee_percent` DECIMAL(5,2) NOT NULL DEFAULT 30.00,
  `subtotal_rate` DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  `subtotal_nett` DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  `catering_fee_amount` DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  `total_restaurant_revenue` DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  `total_transaction` DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  `total_amount` DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  `pax` INT UNSIGNED NULL,
  `date_of_event` DATE NULL,
  `time_of_event` JSON NULL,
  `menu_items` TEXT NULL,
  `kitchen_maintenance` TEXT NULL,
  `marcom` TEXT NULL,
  `billing_instruction` TEXT NULL,
  `prepared_by_name` VARCHAR(255) NULL,
  `prepared_by_title` VARCHAR(255) NULL,
  `acknowledge_by_1_name` VARCHAR(255) NULL,
  `acknowledge_by_1_title` VARCHAR(255) NULL,
  `acknowledge_by_2_name` VARCHAR(255) NULL,
  `acknowledge_by_2_title` VARCHAR(255) NULL,
  `approved_by_name` VARCHAR(255) NULL,
  `approved_by_title` VARCHAR(255) NULL,
  `status` VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
  `created_by` BIGINT UNSIGNED NULL,
  `updated_by` BIGINT UNSIGNED NULL,
  `submitted_at` TIMESTAMP NULL,
  `approved_at` TIMESTAMP NULL,
  `created_at` TIMESTAMP NULL,
  `updated_at` TIMESTAMP NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `sales_lead_reos_sales_lead_id_unique` (`sales_lead_id`),
  UNIQUE KEY `sales_lead_reos_number_unique` (`number`),
  KEY `sales_lead_reos_status_index` (`status`),
  CONSTRAINT `sales_lead_reos_sales_lead_id_foreign` FOREIGN KEY (`sales_lead_id`) REFERENCES `sales_leads` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `sales_lead_reo_approvals` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `reo_id` BIGINT UNSIGNED NOT NULL,
  `approver_id` BIGINT UNSIGNED NOT NULL,
  `approval_level` INT UNSIGNED NOT NULL DEFAULT 1,
  `status` VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  `signature_path` VARCHAR(255) NULL,
  `notes` TEXT NULL,
  `acted_at` TIMESTAMP NULL,
  `created_at` TIMESTAMP NULL,
  `updated_at` TIMESTAMP NULL,
  PRIMARY KEY (`id`),
  KEY `sales_lead_reo_approvals_approver_status_index` (`approver_id`, `status`),
  CONSTRAINT `sales_lead_reo_approvals_reo_id_foreign` FOREIGN KEY (`reo_id`) REFERENCES `sales_lead_reos` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
